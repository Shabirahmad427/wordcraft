#!/usr/bin/env bash
# Reproducible, source-generated DOCX pipeline benchmark. No user documents are read.
set -euo pipefail

if [[ $# -lt 2 || $# -gt 3 ]]; then
  echo "usage: $0 <wordcraft-cli> <new-output-directory> [scale]" >&2
  exit 2
fi

cli=$1
out=$2
scale=${3:-1}
repeats=${BENCH_REPEATS:-3}
if [[ ! -x "$cli" ]]; then
  echo "CLI is not executable: $cli" >&2
  exit 2
fi
if [[ ! "$scale" =~ ^[1-9][0-9]?$ ]] || (( scale > 20 )); then
  echo "scale must be an integer from 1 to 20" >&2
  exit 2
fi
if [[ ! "$repeats" =~ ^[1-9][0-9]?$ ]] || (( repeats > 20 )); then
  echo "BENCH_REPEATS must be an integer from 1 to 20" >&2
  exit 2
fi
if [[ -e "$out" ]] && [[ -n "$(find "$out" -mindepth 1 -maxdepth 1 -print -quit)" ]]; then
  echo "output directory must be absent or empty: $out" >&2
  exit 2
fi
mkdir -p "$out"

docx="$out/synthetic-academic.docx"
pdf="$out/synthetic-academic.pdf"
png="$out/page-1.png"
metrics="$out/metrics.tsv"
printf 'stage\trepetition\twall_seconds\tpeak_rss_kib\tstatus\n' > "$metrics"

measure() {
  local stage=$1
  local repetition=$2
  shift 2
  local timing="$out/.time-$stage"
  local status=0
  if [[ -x /usr/bin/time ]]; then
    /usr/bin/time -f '%e\t%M' -o "$timing" "$@" || status=$?
    if [[ -s "$timing" ]]; then
      IFS=$'\t' read -r elapsed rss < "$timing"
    else
      elapsed=NA
      rss=NA
    fi
  else
    local started=$SECONDS
    "$@" || status=$?
    elapsed=$((SECONDS - started))
    rss=NA
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$stage" "$repetition" "$elapsed" "$rss" "$status" >> "$metrics"
  rm -f "$timing"
  if (( status != 0 )); then
    echo "benchmark stage '$stage' failed with exit $status; see $metrics" >&2
    return "$status"
  fi
}

paragraphs='Synthetic academic performance fixture. It contains citations, equations, captions, section-like headings and repeated prose for predictable pagination.'
for ((i=1; i<=80*scale; i++)); do
  paragraphs+="\\n\\nSection $i. The measured document is generated by WordCraft benchmark tooling. This repeated material exercises paragraph shaping, pagination, line breaking, recovery-safe DOCX import, and PDF text placement. Equation reference (1) and citation [1] are synthetic labels only."
done

commands=(--template report --cmd "text.insert={\"text\":\"$paragraphs\"}")
for ((i=1; i<=8*scale; i++)); do
  commands+=(--cmd 'caret.docEnd' --cmd 'insert.table={"rows":12,"cols":5}')
  commands+=(--cmd 'caret.docEnd' --cmd "insert.chart={\"type\":\"column\",\"title\":\"Synthetic chart $i\",\"data\":{\"categories\":[\"A\",\"B\",\"C\",\"D\"],\"series\":[{\"name\":\"Series 1\",\"values\":[1,3,2,4]},{\"name\":\"Series 2\",\"values\":[2,1,4,3]}]}}")
  commands+=(--cmd 'caret.docEnd' --cmd 'insert.shape={"kind":"rectangle","width":120,"height":64,"fill":"3B82F6"}')
done
for ((i=1; i<=12*scale; i++)); do
  commands+=(--cmd 'caret.docEnd' --cmd "references.footnote={\"text\":\"Synthetic footnote $i with repeated explanatory text for note layout and continuation timing.\"}")
done
for ((i=1; i<=8*scale; i++)); do
  commands+=(--cmd 'caret.docEnd' --cmd "references.endnote={\"text\":\"Synthetic endnote $i with supporting reference metadata used to exercise endnote serialization and pagination.\"}")
done
commands+=(--cmd 'caret.docEnd' --cmd 'insert.equation={"linear":"E=mc^2","edit":false}')

measure generate 1 "$cli" run "${commands[@]}" --save "$docx"
for ((i=1; i<=repeats; i++)); do
  measure load "$i" "$cli" info "$docx"
  measure render "$i" "$cli" render "$docx" "$png" --page 1 --scale 1
  measure pdf-export "$i" "$cli" convert "$docx" "$pdf"
done
printf 'fixture\tsynthetic-academic.docx\nscale\t%s\nrepeats\t%s\n' "$scale" "$repeats" > "$out/manifest.tsv"
printf 'Artifacts: %s\nMetrics: %s\n' "$out" "$metrics"
